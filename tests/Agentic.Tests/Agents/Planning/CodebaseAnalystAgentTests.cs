    private const string Core = "src/UrlShortener.Api/Core/";
    private const string Feat = "src/UrlShortener.Api/Features/";

    /// <summary>A small baseline: weak validator, System.Random codes, three installed slices, hook interfaces and a route group.</summary>
    private static TempWorkspace Baseline(bool hardenedValidator = false)
    {
        var validator = hardenedValidator
            ? "namespace UrlShortener.Api.Core;\npublic static class UrlValidator { public static bool Validate(string? u) => Uri.TryCreate(u, UriKind.Absolute, out var x) && (x.Scheme == Uri.UriSchemeHttps || x.Scheme == Uri.UriSchemeHttp) && !u!.Contains(\"localhost\"); }\n"
            : "namespace UrlShortener.Api.Core;\npublic static class UrlValidator { public static bool Validate(string? u) => Uri.TryCreate(u, UriKind.Absolute, out _); }\n";
        return new TempWorkspace()
            .With(Core + "UrlValidator.cs", validator)
            .With(Core + "CodeGenerator.cs", "namespace UrlShortener.Api.Core;\npublic sealed class CodeGenerator\n{\n    private static readonly Random R = new Random(42);\n    public string Generate() => R.Next().ToString();\n}\n")
            .With(Core + "Routes.cs", "namespace UrlShortener.Api.Core;\npublic static class Routes { public const string Links = \"/api/links\"; }\n")
            .With(Core + "Link.cs", "namespace UrlShortener.Api.Core;\npublic sealed record Link(string Code, string Url);\npublic interface ILinkStore\n{\n    bool TryCreate(Link link);\n    Link? Get(string code);\n    bool Delete(string code);\n}\npublic sealed class InMemoryLinkStore : ILinkStore\n{\n    public bool TryCreate(Link link) => true;\n    public Link? Get(string code) => null;\n    public bool Delete(string code) => false;\n}\n")
            .With(Core + "Hooks.cs", "using System.Text.Json;\nnamespace UrlShortener.Api.Core;\n" +
                "public interface IRequestGate { int Order { get; } Task<object?> BeforeAsync(object context); }\n" +
                "public interface IShortenHook { int Order { get; } Task<string?> ResolveCodeAsync(object c) => Task.FromResult<string?>(null); Task OnShortenAsync(object c) => Task.CompletedTask; Task AfterShortenAsync(object c) => Task.CompletedTask; }\n" +
                "public interface IRedirectHook { int Order { get; } Task BeforeAsync(object c) => Task.CompletedTask; Task AfterAsync(object c) => Task.CompletedTask; }\n" +
                "public static class HookRunner { public static async Task RunAfter(IEnumerable<IRedirectHook> hooks, object c) { foreach (var hook in hooks) await hook.AfterAsync(c); } }\n")
            .With(Core + "RequestGateMiddleware.cs", "namespace UrlShortener.Api.Core;\npublic sealed class RequestGateMiddleware(IEnumerable<IRequestGate> gates)\n{\n    public async Task Invoke(object ctx) { foreach (var g in gates) await g.BeforeAsync(ctx); }\n}\n")
            .With(Feat + "FeatureRegistry.cs", "// <auto-generated>\nnamespace UrlShortener.Api.Features;\npublic static class FeatureRegistry\n{\n    public static IReadOnlyList<UrlShortener.Api.Core.IFeature> All { get; } = new UrlShortener.Api.Core.IFeature[]\n    {\n        new UrlShortener.Api.Features.Shorten.ShortenFeature(),\n        new UrlShortener.Api.Features.Redirect.RedirectFeature(),\n        new UrlShortener.Api.Features.Manage.ManageFeature(),\n    };\n}\n")
            .With(Feat + "Shorten/ShortenFeature.cs", "using UrlShortener.Api.Core;\nnamespace UrlShortener.Api.Features.Shorten;\npublic sealed class ShortenFeature : IFeature\n{\n    public void MapEndpoints(IEndpointRouteBuilder endpoints) => endpoints.MapPost(Routes.Links, ShortenEndpoint.HandleAsync);\n}\n" +
                "public static class ShortenEndpoint\n{\n    public static async Task HandleAsync(IEnumerable<IShortenHook> hooks, ILinkStore store, CodeGenerator gen, string url)\n    {\n        if (!UrlValidator.Validate(url)) return;\n        foreach (var hook in hooks) { await hook.ResolveCodeAsync(url); await hook.OnShortenAsync(url); }\n        store.TryCreate(new Link(gen.Generate(), url));\n    }\n}\n")
            .With(Feat + "Redirect/RedirectFeature.cs", "using UrlShortener.Api.Core;\nnamespace UrlShortener.Api.Features.Redirect;\npublic sealed class RedirectFeature : IFeature\n{\n    public void MapEndpoints(IEndpointRouteBuilder endpoints) => endpoints.MapGet(\"/{code}\", Handle);\n    static async Task Handle(IEnumerable<IRedirectHook> hooks, ILinkStore store, string code)\n    {\n        var link = store.Get(code);\n        foreach (var hook in hooks) await hook.BeforeAsync(link);\n        await HookRunner.RunAfter(hooks, link);\n    }\n}\n")
            .With(Feat + "Manage/ManageFeature.cs", "using UrlShortener.Api.Core;\nnamespace UrlShortener.Api.Features.Manage;\npublic sealed class ManageFeature : IFeature\n{\n    public void MapEndpoints(IEndpointRouteBuilder endpoints)\n    {\n        var group = endpoints.MapGroup(\"/api/links\");\n        group.MapGet(\"/{code}\", (ILinkStore s, string code) => s.Get(code));\n        group.MapDelete(\"/{code}\", (ILinkStore s, string code) => s.Delete(code));\n        endpoints.MapGet(\"/healthz-ish\", () => 1);\n        // endpoints.MapPost(\"/commented/out\", () => 1);\n    }\n}\n")
            .With("tests/UrlShortener.Tests/UrlShortener.Tests.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\"></Project>");
    }

    private static async Task<(AgentResult result, ImpactReport scan, FakeTestRunner runner)> Scan(TempWorkspace ws, FakeTestRunner? runner = null)
    {
        runner ??= new FakeTestRunner();
        var ctx = Kit.Ctx(Kit.Scenario("x", "baseline", "brownfield"), ws, p: new() { ["mode"] = "scan" }, runner: runner);
        var r = await Kit.Run(new CodebaseAnalystAgent(), ctx);
        return (r, Kit.Get<ImpactReport>(r, "codebase-scan"), runner);
    }

    [Fact]
    public async Task Scan_reports_weak_validator_and_system_random_as_findings()
    {
        using var ws = Baseline();
        var (_, scan, _) = await Scan(ws);
        var scheme = scan.Findings.Single(f => f.Id == "FIND-URL-SCHEME");
        Assert.Equal("high", scheme.Severity);
        Assert.Equal("CWE-601", scheme.Cwe);
        Assert.Equal(Core + "UrlValidator.cs", scheme.File);
        Assert.Equal("allow only http/https", scheme.Fix);
        var hosts = scan.Findings.Single(f => f.Id == "FIND-URL-HOSTS");
        Assert.Equal("CWE-918", hosts.Cwe);
        var rnd = scan.Findings.Single(f => f.Id == "FIND-SEC-004");
        Assert.Equal("high", rnd.Severity);
        Assert.Equal("CWE-338", rnd.Cwe);
        Assert.Equal(Core + "CodeGenerator.cs", rnd.File);
        Assert.Equal(4, rnd.Line);
        Assert.NotEmpty(rnd.Fix);
    }

    [Fact]
    public async Task Scan_of_hardened_validator_has_no_url_findings()
    {
        using var ws = Baseline(hardenedValidator: true);
        var (_, scan, _) = await Scan(ws);
        Assert.DoesNotContain(scan.Findings, f => f.Id.StartsWith("FIND-URL-"));
        Assert.Contains(scan.Findings, f => f.Id == "FIND-SEC-004");
    }

    [Fact]
    public async Task Scan_parses_installed_features_from_the_registry()
    {
        using var ws = Baseline();
        var (_, scan, _) = await Scan(ws);
        Assert.Equal(new[] { "shorten", "redirect", "manage" }, scan.InstalledFeatures);
    }

    [Fact]
    public async Task Scan_without_a_registry_has_no_installed_features()
    {
        using var ws = new TempWorkspace().With(Core + "Link.cs", "namespace X;\npublic record Link(string Code);\n");
        var (_, scan, _) = await Scan(ws);
        Assert.Empty(scan.InstalledFeatures);
        Assert.Single(scan.Modules);
        Assert.Equal(new[] { "Link" }, scan.Modules[0].Types);
    }

    [Fact]
    public async Task Scan_extracts_types_usings_hooks_and_routes_including_groups_and_constants()
    {
        using var ws = Baseline();
        var (_, scan, _) = await Scan(ws);
        var hooks = scan.Modules.Single(m => m.Path.EndsWith("Core/Hooks.cs"));
        Assert.Contains("System.Text.Json", hooks.Usings);
        Assert.Contains("IRequestGate", hooks.Types);
        Assert.Contains("HookRunner", hooks.Types);
        var shorten = scan.Modules.Single(m => m.Path.EndsWith("ShortenFeature.cs"));
        Assert.Contains("ShortenFeature", shorten.Types);
        Assert.Equal(new[] { "IFeature" }, shorten.Hooks);
        Assert.Contains(scan.Routes, r => r.Method == "POST" && r.Path == "/api/links" && r.File.EndsWith("ShortenFeature.cs")); // const resolved
        Assert.Contains(scan.Routes, r => r.Method == "GET" && r.Path == "/{code}" && r.File.EndsWith("RedirectFeature.cs"));
        Assert.Contains(scan.Routes, r => r.Method == "GET" && r.Path == "/api/links/{code}");                                      // group prefix
        Assert.Contains(scan.Routes, r => r.Method == "DELETE" && r.Path == "/api/links/{code}");
        Assert.Contains(scan.Routes, r => r.Path == "/healthz-ish");                                                                // outside the group: no prefix
        Assert.DoesNotContain(scan.Routes, r => r.Path.Contains("commented"));                                                      // comments ignored
        // a class that merely consumes IRequestGate is not an implementation
        Assert.Empty(scan.Modules.Single(m => m.Path.EndsWith("RequestGateMiddleware.cs")).Hooks);
    }

    [Fact]
    public async Task Scan_builds_a_dependency_graph_from_declared_type_names()
    {
        using var ws = Baseline();
        var (_, scan, _) = await Scan(ws);
        var deps = scan.DependencyGraph[Feat + "Shorten/ShortenFeature.cs"];
        Assert.Contains(Core + "UrlValidator.cs", deps);
        Assert.Contains(Core + "CodeGenerator.cs", deps);
        Assert.Contains(Core + "Link.cs", deps);
        Assert.Contains(Core + "Routes.cs", deps);
        Assert.DoesNotContain(Feat + "Shorten/ShortenFeature.cs", deps);
        Assert.Empty(scan.DependencyGraph[Core + "UrlValidator.cs"]);
    }

    [Fact]
    public async Task Scan_derives_data_flows_from_the_code()
    {
        using var ws = Baseline();
        var (_, scan, _) = await Scan(ws);
        var create = scan.DataFlows.Single(f => f.StartsWith("POST /api/links"));
        Assert.Contains("ShortenFeature.cs", create);
        Assert.Contains("UrlValidator", create);
        Assert.Contains("CodeGenerator", create);
        Assert.Contains("ILinkStore.TryCreate", create);
        Assert.True(create.IndexOf("UrlValidator") < create.IndexOf("ILinkStore"));
        Assert.Contains("ILinkStore.Get", scan.DataFlows.Single(f => f.StartsWith("GET /{code}")));
        Assert.Contains(scan.DataFlows, f => f.StartsWith("every request → RequestGateMiddleware.cs → IRequestGate.BeforeAsync"));
    }

    [Fact]
    public async Task Scan_resolves_concatenated_and_interpolated_route_templates()
    {
        using var ws = Baseline();
        ws.WriteText(Feat + "Stats/StatsFeature.cs", "using UrlShortener.Api.Core;\nnamespace UrlShortener.Api.Features.Stats;\npublic sealed class StatsFeature : IFeature\n{\n    public void MapEndpoints(IEndpointRouteBuilder e)\n    {\n        e.MapGet(Routes.Links + \"/{code}/stats\", () => 1);\n        e.MapGet($\"{Routes.Links}/{{code}}/qr\", () => 2);\n        e.MapGet(UnknownThing.Value, () => 3);\n        var s = \"MapGet(\\\"/in-a-string\\\"\";\n    }\n}\n");
        var (_, scan, _) = await Scan(ws);
        Assert.Contains(scan.Routes, r => r.Method == "GET" && r.Path == "/api/links/{code}/stats");
        Assert.Contains(scan.Routes, r => r.Method == "GET" && r.Path == "/api/links/{code}/qr");
        Assert.DoesNotContain(scan.Routes, r => r.Path.Contains("in-a-string") || r.Path.Contains("Unknown"));
        Assert.Equal(scan.Routes.OrderBy(r => r.Path, StringComparer.Ordinal).ThenBy(r => r.Method, StringComparer.Ordinal).Select(r => r.Path + r.Method),
            scan.Routes.Select(r => r.Path + r.Method)); // sorted deterministically
    }

    [Fact]
    public async Task Scan_flows_name_the_gate_implementations_and_do_not_leak_unrelated_hooks()
    {
        using var ws = Baseline();
        ws.WriteText(Feat + "Gate/GateFeature.cs", "using UrlShortener.Api.Core;\nnamespace UrlShortener.Api.Features.Gate;\npublic sealed record GateOptions(int Limit);\npublic sealed class MyGate : IRequestGate\n{\n    public int Order => 1;\n    public Task<object?> BeforeAsync(object c) => Task.FromResult<object?>(null);\n}\n");
        var (_, scan, _) = await Scan(ws);
        Assert.Equal(new[] { "IRequestGate" }, scan.Modules.Single(m => m.Path.EndsWith("GateFeature.cs")).Hooks);
        Assert.Contains(scan.DataFlows, f => f.Contains("IRequestGate.BeforeAsync (MyGate)"));
        // the redirect flow must not claim the shorten hook just because both interfaces live in Core/Hooks.cs
        var redirect = scan.DataFlows.Single(f => f.StartsWith("GET /{code}"));
        Assert.DoesNotContain("IShortenHook", redirect);
        Assert.Contains("IRedirectHook", redirect);
    }

    [Fact]
    public async Task Scan_runs_baseline_tests_only_when_the_test_project_exists()
    {
        using var ws = Baseline();
        var runner = new FakeTestRunner { Report = new TestReport(3, 1, 0, 4, 10, 1, new() { "Boom" }, "tail") };
        var (_, scan, _) = await Scan(ws, runner);
        Assert.Single(runner.Calls);
        Assert.Equal(Kit.Catalog.Core.TestProject, runner.Calls[0].project);
        Assert.Equal(ws.Root, runner.Calls[0].root);
        Assert.Equal(1, scan.BaselineTests!.Failed);
        Assert.Empty(scan.Impacted);
        Assert.Empty(scan.NewFiles);

        using var noTests = new TempWorkspace().With(Core + "Link.cs", "namespace X;\npublic record Link(string Code);\n");
        var runner2 = new FakeTestRunner();
        var (_, scan2, _) = await Scan(noTests, runner2);
        Assert.Empty(runner2.Calls);
        Assert.Null(scan2.BaselineTests);
    }

    private static async Task<(ImpactReport impact, AgentResult result)> Impact(TempWorkspace ws, string requirement, Dictionary<string, string>? answers = null)
    {
        var store = new Dictionary<string, JsonNode>();
        var reqCtx = Kit.Ctx(Kit.Scenario(requirement, "baseline", "brownfield"), p: answers is null ? null : Kit.Answers(answers));
        Kit.Publish(store, await Kit.Run(new RequirementsAgent(), reqCtx));
        var (scanResult, _, _) = await Scan(ws);
        Kit.Publish(store, scanResult);
        var ctx = Kit.Ctx(Kit.Scenario(requirement, "baseline", "brownfield"), ws, store, new() { ["mode"] = "impact" });
        var r = await Kit.Run(new CodebaseAnalystAgent(), ctx);
        return (Kit.Get<ImpactReport>(r, "impact"), r);
    }

    [Fact]
    public async Task Impact_lists_hardening_modifications_as_high_risk_with_the_finding_they_fix()
    {
        using var ws = Baseline();
        var (impact, result) = await Impact(ws, "Add link expiry and click analytics");
        Assert.Contains(Core + "UrlValidator.cs", impact.ModifiedFiles);
        Assert.Contains(Core + "CodeGenerator.cs", impact.ModifiedFiles);
        var validator = impact.Impacted.Single(i => i.Path == Core + "UrlValidator.cs");
        Assert.Equal("modify", validator.Change);
        Assert.Equal("high", validator.Risk);
        Assert.Contains("FIND-URL-SCHEME", validator.Reason);
        Assert.Contains("POST /api/links", validator.Reason);
        var generator = impact.Impacted.Single(i => i.Path == Core + "CodeGenerator.cs");
        Assert.Equal("high", generator.Risk);
        Assert.Contains("FIND-SEC-004", generator.Reason);
        Assert.Contains(Kit.Catalog.Core.HardeningTestFile, impact.NewFiles);
        Assert.Contains("POST /api/links now rejects non-http(s) and internal URLs with 400", impact.ApiChanges);
        Assert.Contains(result.Decisions, d => d.Title == $"Modify {Core}UrlValidator.cs");
    }

    [Fact]
    public async Task Impact_registers_new_slices_and_marks_hook_invocation_sites_as_additive()
    {
        using var ws = Baseline();
        var (impact, result) = await Impact(ws, "Add link expiry and click analytics");
        var registry = Kit.Catalog.Core.RegistryPath;
        Assert.Contains(registry, impact.ModifiedFiles);
        var reg = impact.Impacted.Single(i => i.Path == registry);
        Assert.Equal(("modify", "low"), (reg.Change, reg.Risk));
        // expiry uses onShorten/beforeRedirect, analytics uses afterRedirect
        var shortenSite = impact.Impacted.Single(i => i.Path == Feat + "Shorten/ShortenFeature.cs");
        Assert.Equal(("extend", "medium"), (shortenSite.Change, shortenSite.Risk));
        Assert.Contains("onShorten", shortenSite.Reason);
        Assert.Contains("hook invocation site", shortenSite.Reason);
        var redirectSite = impact.Impacted.Single(i => i.Path == Feat + "Redirect/RedirectFeature.cs");
        Assert.Contains("beforeRedirect", redirectSite.Reason);
        var runner = impact.Impacted.Single(i => i.Path == Core + "Hooks.cs");
        Assert.Contains("afterRedirect", runner.Reason);
        Assert.Contains("new endpoint GET /api/links/:code/stats", impact.ApiChanges);
        Assert.Contains("POST /api/links gains optional field ttlSeconds", impact.ApiChanges);
        Assert.Contains("GET /{code} may now return 410 (link_expired) for expired links", impact.ApiChanges);
        Assert.Contains(result.Decisions, d => d.Title == "Do not modify " + Feat + "Shorten/ShortenFeature.cs");
        // installed features are not re-installed
        Assert.DoesNotContain(impact.NewFiles, f => f.Contains("/Features/Shorten/") && !f.Contains("tests/"));
        // scan data is carried over
        Assert.Equal(new[] { "shorten", "redirect", "manage" }, impact.InstalledFeatures);
        Assert.NotEmpty(impact.Findings);
        Assert.NotEmpty(impact.DependencyGraph);
    }

    [Fact]
    public async Task Impact_skips_hardening_when_the_codebase_has_no_blocking_findings()
    {
        using var ws = Baseline(hardenedValidator: true);
        // replace System.Random so no findings at all remain
        ws.WriteText(Core + "CodeGenerator.cs", "using System.Security.Cryptography;\nnamespace UrlShortener.Api.Core;\npublic sealed class CodeGenerator { public string Generate() => RandomNumberGenerator.GetInt32(10).ToString(); }\n");
        var (impact, _) = await Impact(ws, "Add link expiry");
        Assert.DoesNotContain(Core + "UrlValidator.cs", impact.ModifiedFiles);
        Assert.DoesNotContain(impact.Impacted, i => i.Risk == "high");
        Assert.DoesNotContain(impact.ApiChanges, c => c.Contains("rejects non-http"));
    }

    [Fact]
    public async Task Impact_output_is_deterministic()
    {
        using var ws = Baseline();
        var (a, _) = await Impact(ws, "Add link expiry and click analytics");
        var (b, _) = await Impact(ws, "Add link expiry and click analytics");
        Assert.Equal(Json.Serialize(a), Json.Serialize(b));
    }
